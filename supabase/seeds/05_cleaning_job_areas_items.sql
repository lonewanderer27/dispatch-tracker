-- Local development seed 5 of 5: the areas and items each seeded cleaning job covers.
-- NEVER run against a hosted project. Needs 02_reference_data.sql (areas, items, cleaning types)
-- and 04_cleaning_jobs.sql (the jobs and their cleaning types).
-- Source: the cleaning type of each job and the things named in its notes in the anonymised
-- copy of The Tidy Team Schedule (oven, fridge, cabinets, windows, baseboards, walls, carpet,
-- basement). Safe to run more than once.

-- Areas by cleaning type. A job with several types gets the union; priority is true if any of
-- its types marks the area as a priority. Kitchen and Bathroom are the priority areas of the
-- thorough cleans (Deep, Move-In, Move-Out, Diamond Cleaning).
insert into public.cleaning_job_areas (cleaning_job_id, area_id, priority)
select jct.cleaning_job_id, a.id, bool_or(m.priority)
from public.cleaning_job_cleaning_types jct
join public.cleaning_types ct on ct.id = jct.cleaning_type_id
join (values
  ('Regular', 'Kitchen', false), ('Regular', 'Bathroom', false), ('Regular', 'Living Area', false), ('Regular', 'Floor', false),
  ('Deep', 'Kitchen', true), ('Deep', 'Bathroom', true), ('Deep', 'Bedroom', false), ('Deep', 'Living Area', false),
  ('Deep', 'Dining Room', false), ('Deep', 'Hallway', false), ('Deep', 'Floor', false),
  ('Move-In', 'Kitchen', true), ('Move-In', 'Bathroom', true), ('Move-In', 'Bedroom', false), ('Move-In', 'Living Area', false),
  ('Move-In', 'Hallway', false), ('Move-In', 'Floor', false),
  ('Move-Out', 'Kitchen', true), ('Move-Out', 'Bathroom', true), ('Move-Out', 'Bedroom', false), ('Move-Out', 'Living Area', false),
  ('Move-Out', 'Hallway', false), ('Move-Out', 'Floor', false),
  ('Construction', 'Living Area', false), ('Construction', 'Floor', false),
  ('Diamond Cleaning', 'Kitchen', true), ('Diamond Cleaning', 'Bathroom', true), ('Diamond Cleaning', 'Bedroom', false),
  ('Diamond Cleaning', 'Living Area', false), ('Diamond Cleaning', 'Dining Room', false), ('Diamond Cleaning', 'Hallway', false),
  ('Diamond Cleaning', 'Floor', false)
) as m(type_name, area_name, priority) on m.type_name = ct.name
join public.areas a on a.name = m.area_name
where jct.cleaning_job_id::text like 'e3000000%'
group by jct.cleaning_job_id, a.id
on conflict (cleaning_job_id, area_id) do nothing;

